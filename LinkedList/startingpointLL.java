/*Definition of singly linked list:
class ListNode {
    int val;
    ListNode next;

    ListNode() {
        val = 0;
        next = null;
    }

    ListNode(int data1) {
        val = data1;
        next = null;
    }

    ListNode(int data1, ListNode next1) {
        val = data1;
        next = next1;
    }
}
 */

class Solution {
    public ListNode findStartingPoint(ListNode head) {
        HashSet<ListNode>st=new HashSet<>();

        ListNode temp=head;

        while(temp!=null){
            if(st.contains(temp)){
                return temp;
            }
            st.add(temp);
            temp=temp.next;
        }
        return null;

    }
}

