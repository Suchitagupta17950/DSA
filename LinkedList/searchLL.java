class Solution {
    public boolean searchKey(ListNode head, int key) {
        // Your code goes here
        if(head==null){
            return false;
        }
        ListNode temp=head;
        while(temp!=null){
            if(temp.data==key){
                return true;
            }
            temp=temp.next;
        }
        return false;
    }
}
